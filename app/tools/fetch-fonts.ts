// Downloads the app's fonts (Onest, Noto Sans TC, JetBrains Mono; SIL OFL 1.1) from Google Fonts
// into src/fonts so the app renders the same offline. Run: bun tools/fetch-fonts.ts
import { mkdirSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const URL = 'https://fonts.googleapis.com/css2?family=Onest:wght@400..600&family=Noto+Sans+TC:wght@400..600&family=JetBrains+Mono:wght@400..500&display=swap';
const UA = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0 Safari/537.36';
const out = join(import.meta.dir, '..', 'src', 'fonts');

const res = await fetch(URL, { headers: { 'user-agent': UA } });
if (!res.ok) throw new Error(`fonts css: HTTP ${res.status}`);
let css = await res.text();
rmSync(out, { recursive: true, force: true });
mkdirSync(join(out, 'files'), { recursive: true });

const urls = [...new Set([...css.matchAll(/url\((https:[^)]+\.woff2)\)/g)].map((m) => m[1]))];
let n = 0;
await Promise.all(urls.map(async (u) => {
  const r = await fetch(u);
  if (!r.ok) throw new Error(`${u}: HTTP ${r.status}`);
  const name = u.split('/s/')[1].replaceAll('/', '-');
  writeFileSync(join(out, 'files', name), new Uint8Array(await r.arrayBuffer()));
  css = css.replaceAll(u, `./files/${name}`);
  n++;
}));
writeFileSync(join(out, 'fonts.css'), `/* Generated by tools/fetch-fonts.ts. Fonts: SIL Open Font License 1.1. */\n${css}`);
console.log(`saved ${n} files to ${out}`);
