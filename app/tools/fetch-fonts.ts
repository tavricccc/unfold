// Builds the app's bundled fonts into src/fonts so the app renders the same offline. All SIL OFL 1.1.
//   Latin: Instrument Sans and DM Mono, downloaded from Google Fonts.
//   Han:   GenYo Gothic TW (源樣黑體, github.com/buttaiwan/genyog-font), cut into woff2 slices along the
//          unicode-range split Google uses for Noto Sans TC, so a page loads only the slices it shows.
// Run: bun tools/fetch-fonts.ts   (needs Python with fonttools and brotli; FONT_CACHE keeps the OTF downloads)
import { spawnSync } from 'node:child_process';
import { existsSync, mkdirSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

const UA = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0 Safari/537.36';
const LATIN = 'https://fonts.googleapis.com/css2?family=Instrument+Sans:wght@400..600&family=DM+Mono:wght@400;500&display=swap';
const SPLIT = 'https://fonts.googleapis.com/css2?family=Noto+Sans+TC:wght@400&display=swap';
const GENYO = 'https://raw.githubusercontent.com/buttaiwan/genyog-font/master/otf/TW';
const WEIGHTS: [file: string, css: string][] = [['R', '400'], ['M', '500'], ['B', '600 700']];

const out = join(import.meta.dir, '..', 'src', 'fonts');
const cache = process.env.FONT_CACHE ?? join(tmpdir(), 'unfold-fonts');

async function css(url: string) {
  const res = await fetch(url, { headers: { 'user-agent': UA } });
  if (!res.ok) throw new Error(`${url}: HTTP ${res.status}`);
  return res.text();
}

async function download(url: string, to: string) {
  const r = await fetch(url);
  if (!r.ok) throw new Error(`${url}: HTTP ${r.status}`);
  writeFileSync(to, new Uint8Array(await r.arrayBuffer()));
}

rmSync(out, { recursive: true, force: true });
mkdirSync(join(out, 'files'), { recursive: true });
mkdirSync(cache, { recursive: true });

// Latin faces, as Google serves them.
let latin = await css(LATIN);
const urls = [...new Set([...latin.matchAll(/url\((https:[^)]+\.woff2)\)/g)].map((m) => m[1]))];
await Promise.all(urls.map(async (u) => {
  const name = u.split('/s/')[1].replaceAll('/', '-');
  await download(u, join(out, 'files', name));
  latin = latin.replaceAll(u, `./files/${name}`);
}));

// The slice plan: each Noto Sans TC block's unicode-range.
const ranges = [...(await css(SPLIT)).matchAll(/unicode-range:\s*([^;]+);/g)].map((m) => m[1].trim());
const slices = ranges.map((r, i) => [String(i), r.split(',').map((part) => {
  const [a, b] = part.trim().replace(/^U\+/i, '').split('-');
  return [parseInt(a, 16), parseInt(b ?? a, 16)];
})]);
const plan = join(cache, 'slices.json');
writeFileSync(plan, JSON.stringify(slices));

let han = '';
for (const [w, weight] of WEIGHTS) {
  const otf = join(cache, `GenYoGothic2TW-${w}.otf`);
  if (!existsSync(otf)) await download(`${GENYO}/GenYoGothic2TW-${w}.otf`, otf);
  const run = spawnSync('python', [join(import.meta.dir, 'genyo-slices.py'), otf, join(out, 'files'), `genyo-${w}`, plan], { encoding: 'utf8', maxBuffer: 1 << 24 });
  if (run.status !== 0) throw new Error(`slicing ${w}: ${run.stderr}`);
  for (const name of run.stdout.split(/\s+/).filter(Boolean)) {
    han += `@font-face {\n  font-family: 'GenYo Gothic TW';\n  font-style: normal;\n  font-weight: ${weight};\n  font-display: swap;\n`
      + `  src: url(./files/genyo-${w}-${name}.woff2) format('woff2');\n  unicode-range: ${ranges[Number(name)]};\n}\n`;
  }
}

writeFileSync(join(out, 'fonts.css'), `/* Generated by tools/fetch-fonts.ts. Fonts: SIL Open Font License 1.1. */\n${latin}${han}`);
console.log(`saved ${readdirSync(join(out, 'files')).length} files to ${out}`);
